-- رصيد سابق (opening balance) لعميل المذخر: دَين متراكم من قبل انضمام هذا
-- المذخر للمنصة — من أي نظام كان يستخدمه سابقاً (دفتر ورقي، إكسل، برنامج
-- آخر). فاتورة مرجعية حقيقية أظهرت "الرصيد السابق : 3,800,076" كرقم منفصل
-- عن حركة الفواتير داخل هذا النظام، بينما WarehouseCustomer لم يكن يخزّن أي
-- شيء مماثل — فكل مذخر جديد ينضم للمنصة يُظهر رصيداً سابقاً صفرياً لكل
-- عملائه، وهو كذب صريح، وحدّ الائتمان يُفحص ضد دَين مُستَهان به.
--
-- لماذا الآن: صاحب النظام طلب صراحة أن يُدار هذا الرصيد من صفحة العملاء
-- (app/warehouse/customers) — إدخال يدوي عند الإعداد لكل صيدلية، وليس رقماً
-- يُشتق أو يُعاد حسابه تلقائياً من أي شيء. كل رقم "مستحق" بعد هذا التعديل =
-- openingBalance + مجموع فواتير المنصة المفتوحة + مجموع مبيعات المندوبين
-- الميدانية المفتوحة (الدالة النقيّة الموحَّدة outstandingWithOpeningBalance
-- في app/lib/warehouse-accounts.ts، المُستدعاة من كل مواضع حساب "المستحق").
--
-- لماذا NOT NULL DEFAULT 0 آمن على قاعدة حيّة، بخلاف عمودَي هجرة 20260919
-- (nullable بلا DEFAULT لأنهما "وعد" قد يغيب فعلاً):
--   * القيمة الافتراضية هنا ثابتة (0) لا تعبيراً حسابياً على أعمدة أخرى —
--     على PostgreSQL 11+‎ إضافة عمود NOT NULL بقيمة DEFAULT ثابتة عملية
--     تعديل metadata فقط في كتالوج النظام، بلا إعادة كتابة الجدول (table
--     rewrite) وبلا قفل طويل يحجب القراءة/الكتابة أثناء التنفيذ — الإصدار
--     المستهدف هنا حديث (نفس افتراض هجرات هذا المشروع السابقة على
--     Float @default(0) مثل creditLimit وpaymentTermDays في هجرة
--     20260907000000_warehouse_accounts).
--   * 0 هو المعنى الصحيح فعلياً لكل صفّ WarehouseCustomer موجود حالياً: لا
--     أحد أدخل رصيداً سابقاً بعد (الحقل لم يكن موجوداً أصلاً)، و"لا رصيد
--     سابق مسجَّل" هو بالضبط ما يعنيه 0 هنا — بخلاف batchNumber/expiryDate
--     في الهجرة السابقة حيث NULL ("لم يُصرَّح بعد") كانت الدلالة الصحيحة
--     الوحيدة لعمود اختياري بطبيعته. هذا العمود غير اختياري بطبيعته: كل
--     عميل له رصيد سابق حتى لو كان صفراً، فـNOT NULL هي القيد الصحيح.
--   * لا تعبئة رجعية (backfill) بخلاف 0: لا مصدر بيانات موثوق لاستنتاج
--     رصيد سابق من داخل هذا النظام نفسه — الرصيد السابق بحكم تعريفه من
--     خارج النظام، وإدخاله مسؤولية بشرية يدوية من صفحة العملاء لاحقاً.
--   * لا قيود ولا فهارس جديدة: عمود مالي عادي يُقرأ كاملاً مع الصف نفسه في
--     كل موضع (لا يُفلتر أو يُرتَّب به استعلام)، تماماً كـcreditLimit.
--   * لا استعلام قائم يتغيّر سلوكه تلقائياً بهذه الهجرة وحدها — القيمة 0
--     تحافظ على كل حساب "مستحق" الحالي كما هو تماماً إلى أن يُدخِل مالك
--     المذخر رصيداً سابقاً حقيقياً يدوياً؛ التعديل البرمجي المصاحب (قراءة
--     هذا الحقل وإضافته للمستحق) منفصل عن هذه الهجرة ولا يُغيّر منها شيئاً.

ALTER TABLE "WarehouseCustomer" ADD COLUMN "openingBalance" DOUBLE PRECISION NOT NULL DEFAULT 0;
