async def generate_audio():
    if not os.path.exists(OUTPUT_DIR):
        os.makedirs(OUTPUT_DIR)
        
    print(f"Generating full voiceovers using voice: {VOICE}")
    for idx, part in enumerate(PARTS):
        filename = part['filename']
        text = part['text']
        print(f"[{idx+1}/{len(PARTS)}] Generating {filename} ...")
        
        communicate = edge_tts.Communicate(text, VOICE, rate=RATE, pitch=PITCH)
        await communicate.save(os.path.join(OUTPUT_DIR, filename))
        
    print(f"\nAll files generated successfully in:\n{OUTPUT_DIR}")

if __name__ == '__main__':
    asyncio.run(generate_audio())
